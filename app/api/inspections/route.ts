import { appUrl } from '@/lib/app-url'
import { createClient } from '@/lib/supabase/server'
import { NextRequest, NextResponse } from 'next/server'

export const runtime = 'nodejs'

// ─── GET /api/inspections?draw_request_id=xxx ────────────────────────────────
export async function GET(request: NextRequest) {
  const supabase = createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  const { data: profile } = await supabase.from('profiles').select('role').eq('id', user.id).single()
  if (!profile || !['admin', 'lender'].includes(profile.role)) {
    return NextResponse.json({ error: 'Forbidden' }, { status: 403 })
  }

  const drawId = request.nextUrl.searchParams.get('draw_request_id')
  if (!drawId) return NextResponse.json({ error: 'draw_request_id required' }, { status: 400 })

  const { data, error } = await supabase
    .from('inspections')
    .select('*')
    .eq('draw_request_id', drawId)
    .order('created_at', { ascending: false })

  if (error) return NextResponse.json({ error: error.message }, { status: 500 })
  return NextResponse.json({ data })
}

// ─── POST /api/inspections ────────────────────────────────────────────────────
export async function POST(request: NextRequest) {
  const supabase = createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  const { data: profile } = await supabase.from('profiles').select('role').eq('id', user.id).single()
  if (!profile || profile.role !== 'admin') {
    return NextResponse.json({ error: 'Admin only' }, { status: 403 })
  }

  const body = await request.json()
  const { draw_request_id, project_id, inspector_name, inspector_email, scheduled_date } = body

  if (!draw_request_id || !inspector_name || !inspector_email) {
    return NextResponse.json({ error: 'draw_request_id, inspector_name, inspector_email required' }, { status: 400 })
  }

  // Fetch draw + project info for the email (and the draw's project_id: the
  // nested projects(...) select carries no id, and inspections.project_id
  // must be set or the lender / borrower policies can't see the row)
  const { data: draw } = await supabase
    .from('draw_requests')
    .select('project_id, request_number, amount, projects(name, address, city, state)')
    .eq('id', draw_request_id)
    .single()

  // Insert inspection — token is auto-generated by DB default
  const { data: inspection, error } = await supabase
    .from('inspections')
    .insert({
      draw_request_id,
      project_id: project_id ?? (draw as any)?.project_id,
      inspector_name,
      inspector_email,
      scheduled_date: scheduled_date || null,
      created_by: user.id,
    })
    .select()
    .single()

  if (error) return NextResponse.json({ error: error.message }, { status: 500 })

  // Send inspection request email to the inspector
  const baseUrl = appUrl()
  const portalUrl = `${baseUrl}/inspect/${inspection.token}`
  // Names and addresses are typed by people; escape them before they go into HTML.
  const esc = (v: unknown) => String(v ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
  const project = (draw as any)?.projects

  const emailMessage = {
    to: [inspector_email],
      subject: `Inspection Request — ${project?.name ?? 'BuildChain Project'} · ${draw?.request_number ?? ''}`,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; background: #0d1b2a; color: #e8edf2; padding: 32px; border-radius: 12px;">
          <img src="${baseUrl}/brand/buildchain-logo-reverse-email.png" width="220" height="76" alt="BuildChain" style="display: block; border: 0; margin-bottom: 8px;"/>
          <div style="font-size: 12px; color: #6b8198; margin-bottom: 24px; text-transform: uppercase; letter-spacing: 1px;">
            Inspection Request
          </div>

          <h2 style="font-size: 18px; font-weight: 700; margin: 0 0 8px;">Hello ${esc(inspector_name)},</h2>
          <p style="color: #9ab0c7; margin: 0 0 24px;">
            You have been assigned to inspect the following construction draw:
          </p>

          <div style="background: rgba(255,255,255,0.05); border: 1px solid #1e3a50; border-radius: 8px; padding: 16px; margin-bottom: 24px;">
            <div style="font-size: 13px; color: #6b8198; margin-bottom: 4px;">PROJECT</div>
            <div style="font-weight: 700; font-size: 16px; margin-bottom: 12px;">${esc(project?.name ?? '—')}</div>

            <div style="font-size: 13px; color: #6b8198; margin-bottom: 4px;">ADDRESS</div>
            <div style="margin-bottom: 12px;">${esc([project?.address, project?.city, project?.state].filter(Boolean).join(', ') || '—')}</div>

            <div style="font-size: 13px; color: #6b8198; margin-bottom: 4px;">DRAW REQUEST</div>
            <div style="margin-bottom: 12px;">${draw?.request_number ?? '—'}</div>

            ${scheduled_date ? `
            <div style="font-size: 13px; color: #6b8198; margin-bottom: 4px;">SCHEDULED DATE</div>
            <div style="margin-bottom: 12px;">${new Date(scheduled_date).toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric' })}</div>
            ` : ''}
          </div>

          <p style="color: #9ab0c7; margin-bottom: 20px;">
            After completing your on-site inspection, please submit your report using the secure portal link below:
          </p>

          <a href="${portalUrl}"
            style="display: inline-block; background: #c9a457; color: #0d1b2a; font-weight: 700; padding: 14px 28px; border-radius: 8px; text-decoration: none; font-size: 15px;">
            Submit Inspection Report →
          </a>

          <p style="color: #6b8198; font-size: 12px; margin-top: 24px;">
            This link is unique to you.
            If you have questions, reply to this email.
          </p>
        </div>
      `,
  }

  // Send it here rather than through lib/email/send.ts: that helper returns
  // nothing, so the admin could not be told whether the email actually went.
  let emailSent = false
  let emailError: string | null = null
  const apiKey = process.env.RESEND_API_KEY
  const from = process.env.EMAIL_FROM
  if (!apiKey || !from || apiKey === 're_your_key_here') {
    emailError = 'Email is not configured on this server'
  } else {
    try {
      const { Resend } = await import('resend')
      const { error: sendErr } = await new Resend(apiKey).emails.send({ from, ...emailMessage })
      if (sendErr) emailError = sendErr.message ?? 'The email service refused the message'
      else emailSent = true
    } catch (emailErr) {
      emailError = emailErr instanceof Error ? emailErr.message : String(emailErr)
    }
  }
  if (!emailSent) console.warn('[Inspections] Email not sent (non-fatal):', emailError)

  // Log to activity
  const { error: logErr } = await supabase.from('activity_log').insert({
    action: 'inspection_assigned',
    user_id: user.id,
    details: { inspector_name, inspector_email, draw_request_id, inspection_id: inspection.id, email_sent: emailSent },
  })
  if (logErr) console.warn('[Inspections] inspection_assigned was not logged:', logErr.message)

  return NextResponse.json(
    { data: inspection, email_sent: emailSent, email_error: emailSent ? null : emailError, inspect_url: portalUrl },
    { status: 201 }
  )
}
